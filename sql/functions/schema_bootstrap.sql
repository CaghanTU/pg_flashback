BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'tracked_tables'
          AND column_name = 'replica_identity_was'
    ) THEN
        ALTER TABLE flashback.tracked_tables ADD COLUMN replica_identity_was "char" NOT NULL DEFAULT 'd';
    END IF;
END
$$;

-- When the original REPLICA IDENTITY was USING INDEX, store the index name here
-- so flashback_untrack() can restore it exactly. NULL when not applicable.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'tracked_tables'
          AND column_name = 'replica_identity_index'
    ) THEN
        ALTER TABLE flashback.tracked_tables ADD COLUMN replica_identity_index text;
    END IF;

    -- retention_cutoff: latest timestamp up to which retention has deleted events.
    -- flashback_restore raises an error if target_time < retention_cutoff.
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'tracked_tables'
          AND column_name = 'retention_cutoff'
    ) THEN
        ALTER TABLE flashback.tracked_tables ADD COLUMN retention_cutoff TIMESTAMPTZ;
    END IF;
END
$$;

