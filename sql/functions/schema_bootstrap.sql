CREATE OR REPLACE FUNCTION flashback_guard_generation_payload_retirement()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, flashback
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'pg_flashback: generation payload retirement audit % is immutable',
            OLD.retirement_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'retiring' THEN
            RAISE EXCEPTION 'pg_flashback: generation payload retirement must start as retiring'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.state = 'removed' THEN
        RAISE EXCEPTION 'pg_flashback: removed payload retirement audit % is immutable',
            OLD.retirement_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NEW.retirement_id IS DISTINCT FROM OLD.retirement_id
       OR NEW.generation_id IS DISTINCT FROM OLD.generation_id
       OR NEW.tracking_id IS DISTINCT FROM OLD.tracking_id
       OR NEW.reason IS DISTINCT FROM OLD.reason
       OR NEW.requested_at IS DISTINCT FROM OLD.requested_at
       OR NEW.requested_by IS DISTINCT FROM OLD.requested_by
       OR NEW.intent_txid IS DISTINCT FROM OLD.intent_txid
       OR NEW.snapshot_id IS DISTINCT FROM OLD.snapshot_id
       OR NEW.snapshot_table IS DISTINCT FROM OLD.snapshot_table
       OR NEW.snapshot_rel_oid IS DISTINCT FROM OLD.snapshot_rel_oid
       OR NEW.snapshot_row_count IS DISTINCT FROM OLD.snapshot_row_count
       OR NEW.snapshot_schema_fingerprint IS DISTINCT FROM OLD.snapshot_schema_fingerprint
       OR NEW.snapshot_storage_backend IS DISTINCT FROM OLD.snapshot_storage_backend
       OR NEW.snapshot_locator IS DISTINCT FROM OLD.snapshot_locator
       OR NEW.expected_delta_rows IS DISTINCT FROM OLD.expected_delta_rows
       OR NEW.expected_schema_rows IS DISTINCT FROM OLD.expected_schema_rows
       OR NEW.first_delta_lsn IS DISTINCT FROM OLD.first_delta_lsn
       OR NEW.last_delta_lsn IS DISTINCT FROM OLD.last_delta_lsn
       OR NEW.details IS DISTINCT FROM OLD.details
       OR NEW.state <> 'removed'
    THEN
        RAISE EXCEPTION 'pg_flashback: invalid payload retirement transition for audit %',
            OLD.retirement_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS generation_payload_retirements_guard
