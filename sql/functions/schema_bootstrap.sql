-- A generation is an immutable restore chain anchored by one exact boundary.
-- The nullable snapshot/stream links support backup generations and the
-- deliberately unqualified legacy state during migration.
CREATE TABLE IF NOT EXISTS flashback.coverage_generations (
    generation_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_id            BIGINT NOT NULL,
    generation_no          BIGINT NOT NULL CHECK (generation_no > 0),
    parent_generation_id   BIGINT,
    stream_id              BIGINT,
    recovery_profile       TEXT NOT NULL
                           CHECK (recovery_profile IN ('local_delta', 'backup')),
    state                  TEXT NOT NULL DEFAULT 'building'
                           CHECK (state IN ('building', 'active', 'sealed', 'retired', 'aborted')),
    boundary_kind          TEXT NOT NULL CHECK (btrim(boundary_kind) <> ''),
    rel_oid_at_boundary    OID NOT NULL,
    boundary_snapshot_id   BIGINT,
    backup_anchor_id       BIGINT,
    canonical_coordinate_kind TEXT GENERATED ALWAYS AS (
        CASE recovery_profile
            WHEN 'local_delta' THEN 'commit_lsn'
            WHEN 'backup' THEN 'physical_lsn'
        END
    ) STORED,
    -- A transaction cannot know its own commit time/COMMIT LSN. A building
    -- generation therefore carries a pending XID/marker until a later
    -- qualification step resolves the exact boundary coordinates.
    boundary_xid           BIGINT,
    boundary_marker        TEXT CHECK (boundary_marker IS NULL OR btrim(boundary_marker) <> ''),
    boundary_time          TIMESTAMPTZ,
    boundary_lsn           PG_LSN,
    valid_through_time     TIMESTAMPTZ,
    valid_through_lsn      PG_LSN,
    -- Exclusive upper applicability bound. Capture completeness remains in
    -- valid_through_*; these fields say when a successor generation takes over.
    superseded_before_time TIMESTAMPTZ,
    superseded_before_lsn  PG_LSN,
    restored_target_time   TIMESTAMPTZ,
    restored_target_lsn    PG_LSN,
    activated_at           TIMESTAMPTZ,
    sealed_at              TIMESTAMPTZ,
    retired_at             TIMESTAMPTZ,
    aborted_at             TIMESTAMPTZ,
    state_reason           TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    details                JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT coverage_generations_tracking_number_key
        UNIQUE (tracking_id, generation_no),
    CONSTRAINT coverage_generations_generation_tracking_key
        UNIQUE (generation_id, tracking_id),
    CONSTRAINT coverage_generations_generation_tracking_stream_key
        UNIQUE (generation_id, tracking_id, stream_id),
    CONSTRAINT coverage_generations_tracking_profile_fk
        FOREIGN KEY (tracking_id, recovery_profile)
        REFERENCES flashback.tracking_lifecycles(tracking_id, recovery_profile)
        ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT coverage_generations_parent_tracking_fk
        FOREIGN KEY (parent_generation_id, tracking_id)
        REFERENCES flashback.coverage_generations(generation_id, tracking_id)
        ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT coverage_generations_stream_fk
        FOREIGN KEY (stream_id)
        REFERENCES flashback.capture_streams(stream_id)
        ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT coverage_generations_boundary_snapshot_tracking_fk
        FOREIGN KEY (boundary_snapshot_id, tracking_id, boundary_lsn)
        REFERENCES flashback.snapshots(snapshot_id, tracking_id, snapshot_lsn)
        ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT coverage_generations_backup_anchor_tracking_lsn_fk
        FOREIGN KEY (backup_anchor_id, tracking_id, boundary_lsn)
        REFERENCES flashback.backup_anchors(
            backup_anchor_id, tracking_id, backup_stop_lsn
        )
        ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT coverage_generations_lsn_order_check
        CHECK (valid_through_lsn IS NULL OR boundary_lsn IS NULL
               OR valid_through_lsn >= boundary_lsn),
    CONSTRAINT coverage_generations_superseded_lsn_order_check
        CHECK (superseded_before_lsn IS NULL OR boundary_lsn IS NULL
               OR superseded_before_lsn > boundary_lsn),
    CONSTRAINT coverage_generations_watermark_applicability_lsn_check
        CHECK (valid_through_lsn IS NULL OR superseded_before_lsn IS NULL
               OR valid_through_lsn <= superseded_before_lsn),
    CONSTRAINT coverage_generations_profile_shape_check CHECK (
        (
            recovery_profile = 'local_delta'
            AND stream_id IS NOT NULL
            AND boundary_snapshot_id IS NOT NULL
            AND backup_anchor_id IS NULL
        ) OR (
            recovery_profile = 'backup'
            AND stream_id IS NULL
            AND boundary_snapshot_id IS NULL
            AND (
                state IN ('building', 'aborted')
                OR (
                    backup_anchor_id IS NOT NULL
                    AND boundary_lsn IS NOT NULL
                    AND valid_through_lsn IS NOT NULL
                )
            )
        )
    ),
    CONSTRAINT coverage_generations_state_shape_check CHECK (
        (
            state = 'building'
            AND (
                (boundary_time IS NOT NULL AND boundary_lsn IS NOT NULL)
                OR boundary_xid IS NOT NULL
                OR boundary_marker IS NOT NULL
            )
        )
        OR (
            state = 'active'
            AND activated_at IS NOT NULL
            AND boundary_time IS NOT NULL
            AND boundary_lsn IS NOT NULL
            AND valid_through_lsn IS NOT NULL
        )
        OR (
            state = 'sealed'
            AND sealed_at IS NOT NULL
            AND boundary_time IS NOT NULL
            AND boundary_lsn IS NOT NULL
            AND valid_through_lsn IS NOT NULL
        )
        OR (
            state = 'retired'
            AND retired_at IS NOT NULL
            AND boundary_time IS NOT NULL
            AND boundary_lsn IS NOT NULL
            AND valid_through_lsn IS NOT NULL
        )
        OR (
            state = 'aborted'
            AND aborted_at IS NOT NULL
        )
    ),
    CONSTRAINT coverage_generations_applicability_shape_check CHECK (
        (
            state IN ('building', 'active', 'aborted')
            AND superseded_before_time IS NULL
            AND superseded_before_lsn IS NULL
        ) OR (
            state IN ('sealed', 'retired')
            AND superseded_before_lsn IS NOT NULL
        )
    )
);

