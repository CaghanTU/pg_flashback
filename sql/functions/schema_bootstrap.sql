-- Once a generation is eligible, its ownership, boundary and applicability
-- identity are immutable. Only monotonic watermark advancement and the
-- successful lifecycle transitions building -> active -> sealed -> retired
-- remain legal. Failed, never-eligible building drafts become immutable
-- `aborted` audit tombstones after their physical payload is removed.
CREATE OR REPLACE FUNCTION flashback_guard_coverage_generation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, flashback
AS $$
DECLARE
    v_capture_mode text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'pg_flashback: generation % is immutable', OLD.generation_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.state NOT IN ('building', 'active') THEN
            RAISE EXCEPTION 'pg_flashback: a generation must be created as building or active'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    ELSE
        IF OLD.state IN ('retired', 'aborted') THEN
            RAISE EXCEPTION 'pg_flashback: terminal generation % is immutable', OLD.generation_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;

        IF NOT (
            NEW.state = OLD.state
            OR (OLD.state = 'building' AND NEW.state = 'active')
            OR (OLD.state = 'building' AND NEW.state = 'aborted')
            OR (OLD.state = 'active' AND NEW.state = 'sealed')
            OR (OLD.state = 'sealed' AND NEW.state = 'retired')
        ) THEN
            RAISE EXCEPTION 'pg_flashback: invalid generation transition % -> %',
                OLD.state, NEW.state
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;

        IF NEW.generation_id IS DISTINCT FROM OLD.generation_id
           OR NEW.tracking_id IS DISTINCT FROM OLD.tracking_id
           OR NEW.generation_no IS DISTINCT FROM OLD.generation_no
           OR NEW.parent_generation_id IS DISTINCT FROM OLD.parent_generation_id
           OR NEW.stream_id IS DISTINCT FROM OLD.stream_id
           OR NEW.recovery_profile IS DISTINCT FROM OLD.recovery_profile
           OR NEW.boundary_kind IS DISTINCT FROM OLD.boundary_kind
           OR NEW.rel_oid_at_boundary IS DISTINCT FROM OLD.rel_oid_at_boundary
           OR NEW.boundary_snapshot_id IS DISTINCT FROM OLD.boundary_snapshot_id
           OR NEW.boundary_xid IS DISTINCT FROM OLD.boundary_xid
           OR NEW.boundary_marker IS DISTINCT FROM OLD.boundary_marker
           OR NEW.restored_target_time IS DISTINCT FROM OLD.restored_target_time
           OR NEW.restored_target_lsn IS DISTINCT FROM OLD.restored_target_lsn
           OR NEW.created_at IS DISTINCT FROM OLD.created_at
        THEN
            RAISE EXCEPTION 'pg_flashback: generation % ownership/lineage is immutable', OLD.generation_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;

        IF OLD.boundary_time IS NOT NULL
           AND NEW.boundary_time IS DISTINCT FROM OLD.boundary_time
        THEN
            RAISE EXCEPTION 'pg_flashback: generation % boundary time is immutable', OLD.generation_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF OLD.boundary_lsn IS NOT NULL
           AND NEW.boundary_lsn IS DISTINCT FROM OLD.boundary_lsn
        THEN
            RAISE EXCEPTION 'pg_flashback: generation % boundary LSN is immutable', OLD.generation_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF OLD.valid_through_lsn IS NOT NULL
           AND (NEW.valid_through_lsn IS NULL
                OR NEW.valid_through_lsn < OLD.valid_through_lsn)
        THEN
            -- Sealing a predecessor across a cross-stream re-anchor may clamp
            -- the watermark down to the exclusive superseded_before bound after
            -- the frontier was inherited by the successor. All other backward
            -- moves remain forbidden.
            IF NOT (
                OLD.state = 'active'
                AND NEW.state = 'sealed'
                AND NEW.superseded_before_lsn IS NOT NULL
                AND NEW.valid_through_lsn IS NOT NULL
                AND NEW.valid_through_lsn = NEW.superseded_before_lsn
                AND NEW.valid_through_lsn <= OLD.valid_through_lsn
            ) THEN
                RAISE EXCEPTION 'pg_flashback: generation % watermark cannot move backward', OLD.generation_id
                    USING ERRCODE = 'integrity_constraint_violation';
            END IF;
        END IF;

        IF NEW.superseded_before_time IS DISTINCT FROM OLD.superseded_before_time
           OR NEW.superseded_before_lsn IS DISTINCT FROM OLD.superseded_before_lsn
        THEN
            IF NOT (OLD.state = 'active' AND NEW.state = 'sealed'
                    AND OLD.superseded_before_time IS NULL
                    AND OLD.superseded_before_lsn IS NULL)
            THEN
                RAISE EXCEPTION 'pg_flashback: generation applicability bound is immutable'
                    USING ERRCODE = 'integrity_constraint_violation';
            END IF;
        END IF;

        IF NEW.activated_at IS DISTINCT FROM OLD.activated_at
           AND NOT (OLD.state = 'building' AND NEW.state = 'active'
                    AND OLD.activated_at IS NULL AND NEW.activated_at IS NOT NULL)
        THEN
            RAISE EXCEPTION 'pg_flashback: invalid generation activation audit change'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.sealed_at IS DISTINCT FROM OLD.sealed_at
           AND NOT (OLD.state = 'active' AND NEW.state = 'sealed'
                    AND OLD.sealed_at IS NULL AND NEW.sealed_at IS NOT NULL)
        THEN
            RAISE EXCEPTION 'pg_flashback: invalid generation seal audit change'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.retired_at IS DISTINCT FROM OLD.retired_at
           AND NOT (OLD.state = 'sealed' AND NEW.state = 'retired'
                    AND OLD.retired_at IS NULL AND NEW.retired_at IS NOT NULL)
        THEN
            RAISE EXCEPTION 'pg_flashback: invalid generation retirement audit change'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.aborted_at IS DISTINCT FROM OLD.aborted_at
           AND NOT (OLD.state = 'building' AND NEW.state = 'aborted'
                    AND OLD.aborted_at IS NULL AND NEW.aborted_at IS NOT NULL)
        THEN
            RAISE EXCEPTION 'pg_flashback: invalid generation abort audit change'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.details IS DISTINCT FROM OLD.details AND OLD.state <> 'building' THEN
            RAISE EXCEPTION 'pg_flashback: qualified generation details are immutable'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;

    -- The present scaffold fails trigger-local generations closed. If T-01
    -- later chooses a proven trigger total-order mechanism, it needs a new
    -- canonical coordinate type and an explicit schema migration.
    IF NEW.recovery_profile = 'local_delta'
       AND NEW.state IN ('active', 'sealed', 'retired')
    THEN
        SELECT capture_mode INTO v_capture_mode
        FROM flashback.capture_streams
        WHERE stream_id = NEW.stream_id;
        IF v_capture_mode IS DISTINCT FROM 'wal' THEN
            RAISE EXCEPTION 'pg_flashback: eligible local generation requires a WAL stream'
                USING ERRCODE = 'integrity_constraint_violation',
                      HINT = 'Trigger capture remains legacy/experimental until policy decision T-01 is implemented.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

