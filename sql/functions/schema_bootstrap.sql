DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'flashback') THEN
        EXECUTE 'CREATE SCHEMA flashback';
    END IF;
END
$$;

DO $$
BEGIN
    IF to_regclass('flashback.delta_log') IS NULL THEN
        -- Partitioned table: PARTITION BY RANGE (committed_at).
        -- Partition pruning in restore queries requires committed_at in WHERE clauses.
        -- PK is (committed_at, event_id) because partition key must be in PK.
        EXECUTE 'CREATE TABLE flashback.delta_log (
            event_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
            event_time      TIMESTAMPTZ NOT NULL DEFAULT now(),
            rel_oid         OID,
            tracking_id     BIGINT,
            generation_id   BIGINT,
            stream_id       BIGINT,
            source_xid      BIGINT,
            committed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
            schema_version  BIGINT NOT NULL DEFAULT 1,
            event_type      TEXT NOT NULL,
            table_name      TEXT NOT NULL,
            old_data        JSONB,
            new_data        JSONB,
            ddl_info        JSONB,
            lsn             PG_LSN,
            commit_lsn      PG_LSN,
            PRIMARY KEY (committed_at, event_id)
        ) PARTITION BY RANGE (committed_at)';
        -- Default partition captures data that doesn''t match any range partition
        EXECUTE 'CREATE TABLE flashback.delta_log_default PARTITION OF flashback.delta_log DEFAULT';
    END IF;
END
$$;

-- Enable lz4 compression on JSONB columns for storage efficiency.
-- Silently skips if server was not built with lz4 support.
DO $$
BEGIN
    IF to_regclass('flashback.delta_log') IS NOT NULL THEN
        BEGIN
            ALTER TABLE flashback.delta_log ALTER COLUMN old_data SET COMPRESSION lz4;
            ALTER TABLE flashback.delta_log ALTER COLUMN new_data SET COMPRESSION lz4;
        EXCEPTION WHEN feature_not_supported THEN
            RAISE NOTICE 'pg_flashback: lz4 compression not available, using default compression for delta_log';
        END;
    END IF;
END
$$;

-- Coverage payload-binding scaffold. These columns remain nullable until the
-- generation runtime is wired atomically. `lsn` is the row-change LSN;
-- `commit_lsn` is the transaction COMMIT LSN used for visibility/watermarks.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'delta_log'
          AND column_name = 'tracking_id'
    ) THEN
        ALTER TABLE flashback.delta_log ADD COLUMN tracking_id BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'delta_log'
          AND column_name = 'generation_id'
    ) THEN
        ALTER TABLE flashback.delta_log ADD COLUMN generation_id BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'delta_log'
          AND column_name = 'stream_id'
    ) THEN
        ALTER TABLE flashback.delta_log ADD COLUMN stream_id BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'delta_log'
          AND column_name = 'commit_lsn'
    ) THEN
        ALTER TABLE flashback.delta_log ADD COLUMN commit_lsn PG_LSN;
    END IF;
END
$$;

CREATE SEQUENCE IF NOT EXISTS flashback.tracking_id_seq;

-- Immutable owner of one track -> untrack lifecycle.  `tracked_tables` below
-- is only the current physical binding; historical generations and incidents
-- must not depend on that mutable/deletable row for referential integrity.
CREATE TABLE IF NOT EXISTS flashback.tracking_lifecycles (
    tracking_id          BIGINT PRIMARY KEY
                         DEFAULT nextval('flashback.tracking_id_seq'),
    recovery_profile     TEXT NOT NULL
                         CHECK (recovery_profile IN ('local_delta', 'backup')),
    initial_rel_oid      OID NOT NULL,
    initial_schema_name  TEXT NOT NULL CHECK (btrim(initial_schema_name) <> ''),
    initial_table_name   TEXT NOT NULL CHECK (btrim(initial_table_name) <> ''),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    created_by           NAME NOT NULL DEFAULT current_user,
    retired_at           TIMESTAMPTZ,
    retired_by           NAME,
    retirement_reason    TEXT,
    retired_rel_oid      OID,
    retired_schema_name  TEXT,
    retired_table_name   TEXT,
    details              JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT tracking_lifecycles_tracking_profile_key
        UNIQUE (tracking_id, recovery_profile),
    CONSTRAINT tracking_lifecycles_retirement_shape_check CHECK (
        (
            retired_at IS NULL
            AND retired_by IS NULL
            AND retirement_reason IS NULL
            AND retired_rel_oid IS NULL
            AND retired_schema_name IS NULL
            AND retired_table_name IS NULL
        ) OR (
            retired_at IS NOT NULL
            AND retired_by IS NOT NULL
            AND retirement_reason IS NOT NULL
            AND btrim(retirement_reason) <> ''
            AND retired_rel_oid IS NOT NULL
            AND retired_schema_name IS NOT NULL
            AND btrim(retired_schema_name) <> ''
            AND retired_table_name IS NOT NULL
            AND btrim(retired_table_name) <> ''
        )
    )
);

CREATE OR REPLACE FUNCTION flashback_guard_tracking_lifecycle_immutable()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, flashback
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'pg_flashback: tracking lifecycle % is immutable', OLD.tracking_id
            USING ERRCODE = 'integrity_constraint_violation',
                  HINT = 'Retire the lifecycle by removing its current tracked_tables binding; do not delete its audit row.';
    END IF;

    IF NEW.tracking_id IS DISTINCT FROM OLD.tracking_id
       OR NEW.recovery_profile IS DISTINCT FROM OLD.recovery_profile
       OR NEW.initial_rel_oid IS DISTINCT FROM OLD.initial_rel_oid
       OR NEW.initial_schema_name IS DISTINCT FROM OLD.initial_schema_name
       OR NEW.initial_table_name IS DISTINCT FROM OLD.initial_table_name
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.details IS DISTINCT FROM OLD.details
    THEN
        RAISE EXCEPTION 'pg_flashback: immutable identity fields of tracking lifecycle % cannot change', OLD.tracking_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.retired_at IS NOT NULL THEN
        IF NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'pg_flashback: retired tracking lifecycle % cannot change', OLD.tracking_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.retired_at IS NULL THEN
        IF NEW.retired_by IS DISTINCT FROM OLD.retired_by
           OR NEW.retirement_reason IS DISTINCT FROM OLD.retirement_reason
           OR NEW.retired_rel_oid IS DISTINCT FROM OLD.retired_rel_oid
           OR NEW.retired_schema_name IS DISTINCT FROM OLD.retired_schema_name
           OR NEW.retired_table_name IS DISTINCT FROM OLD.retired_table_name
        THEN
            RAISE EXCEPTION 'pg_flashback: lifecycle % retirement fields must be written atomically', OLD.tracking_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;

    IF EXISTS (
        SELECT 1 FROM flashback.tracked_tables tt
        WHERE tt.tracking_id = OLD.tracking_id
    ) THEN
        RAISE EXCEPTION 'pg_flashback: lifecycle % still has a current table binding', OLD.tracking_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

