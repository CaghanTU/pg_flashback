-- Migrate every current binding to an immutable lifecycle parent.  This does
-- not create a coverage generation or claim that a legacy boundary is valid.
INSERT INTO flashback.tracking_lifecycles (
    tracking_id, recovery_profile, initial_rel_oid,
    initial_schema_name, initial_table_name, created_at, created_by
)
SELECT
    tt.tracking_id, tt.recovery_profile, tt.rel_oid,
    tt.schema_name, tt.table_name, tt.tracked_since, current_user
FROM flashback.tracked_tables tt
ON CONFLICT (tracking_id) DO NOTHING;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM flashback.tracked_tables tt
        JOIN flashback.tracking_lifecycles tl USING (tracking_id)
        WHERE tl.recovery_profile IS DISTINCT FROM tt.recovery_profile
    ) THEN
        RAISE EXCEPTION 'pg_flashback: current table binding conflicts with immutable lifecycle profile';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.tracked_tables'::regclass
          AND conname = 'tracked_tables_lifecycle_profile_fk'
    ) THEN
        ALTER TABLE flashback.tracked_tables
            ADD CONSTRAINT tracked_tables_lifecycle_profile_fk
            FOREIGN KEY (tracking_id, recovery_profile)
            REFERENCES flashback.tracking_lifecycles(tracking_id, recovery_profile)
            ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED;
    END IF;

    ALTER SEQUENCE flashback.tracking_id_seq
        OWNED BY flashback.tracking_lifecycles.tracking_id;
END
$$;

-- Compatibility bridge for the legacy runtime while lifecycle-aware track is
-- wired: a direct current-binding INSERT creates exactly one parent, and an
-- UPDATE may change the physical binding but never its lifecycle/profile.
CREATE OR REPLACE FUNCTION flashback_bind_current_tracking_lifecycle()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, flashback
AS $$
DECLARE
    v_profile text;
    v_retired_at timestamptz;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.tracking_id IS DISTINCT FROM OLD.tracking_id
           OR NEW.recovery_profile IS DISTINCT FROM OLD.recovery_profile
        THEN
            RAISE EXCEPTION 'pg_flashback: a current binding cannot change lifecycle or recovery profile'
                USING ERRCODE = 'integrity_constraint_violation',
                      HINT = 'Untrack and create a new lifecycle instead.';
        END IF;
        RETURN NEW;
    END IF;

    INSERT INTO flashback.tracking_lifecycles (
        tracking_id, recovery_profile, initial_rel_oid,
        initial_schema_name, initial_table_name, created_at, created_by
    ) VALUES (
        NEW.tracking_id, NEW.recovery_profile, NEW.rel_oid,
        NEW.schema_name, NEW.table_name,
        COALESCE(NEW.tracked_since, clock_timestamp()), current_user
    )
    ON CONFLICT (tracking_id) DO NOTHING;

    SELECT recovery_profile, retired_at
      INTO v_profile, v_retired_at
    FROM flashback.tracking_lifecycles
    WHERE tracking_id = NEW.tracking_id;

    IF v_retired_at IS NOT NULL THEN
        RAISE EXCEPTION 'pg_flashback: retired lifecycle % cannot be rebound', NEW.tracking_id
            USING ERRCODE = 'integrity_constraint_violation',
                  HINT = 'Allocate a new tracking_id for the new tracking lifecycle.';
    END IF;
    IF v_profile IS DISTINCT FROM NEW.recovery_profile THEN
        RAISE EXCEPTION 'pg_flashback: lifecycle % has profile %, not %',
            NEW.tracking_id, v_profile, NEW.recovery_profile
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION flashback_guard_current_tracking_delete()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, flashback
AS $$
BEGIN
    IF to_regclass('flashback.coverage_generations') IS NOT NULL
       AND EXISTS (
           SELECT 1
           FROM flashback.coverage_generations cg
           WHERE cg.tracking_id = OLD.tracking_id
             AND cg.state IN ('building', 'active')
       )
    THEN
        RAISE EXCEPTION 'pg_flashback: lifecycle % still has an eligible or pending generation', OLD.tracking_id
            USING ERRCODE = 'integrity_constraint_violation',
                  HINT = 'Finalize generation retirement under the lifecycle lock before removing the current binding.';
    END IF;
    RETURN OLD;
END;
$$;

CREATE OR REPLACE FUNCTION flashback_retire_tracking_lifecycle()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, flashback
AS $$
BEGIN
    UPDATE flashback.tracking_lifecycles
       SET retired_at = clock_timestamp(),
           retired_by = current_user,
           retirement_reason = 'current_binding_removed',
           retired_rel_oid = OLD.rel_oid,
           retired_schema_name = OLD.schema_name,
           retired_table_name = OLD.table_name
     WHERE tracking_id = OLD.tracking_id
       AND retired_at IS NULL;
    RETURN OLD;
END;
$$;

