CREATE TRIGGER generation_payload_retirements_guard
BEFORE INSERT OR UPDATE OR DELETE ON flashback.generation_payload_retirements
FOR EACH ROW EXECUTE FUNCTION flashback_guard_generation_payload_retirement();

