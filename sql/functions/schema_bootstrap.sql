    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'snapshots'
          AND column_name = 'retired_at'
    ) THEN
        ALTER TABLE flashback.snapshots ADD COLUMN retired_at TIMESTAMPTZ;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'schema_versions'
          AND column_name = 'tracking_id'
    ) THEN
        ALTER TABLE flashback.schema_versions ADD COLUMN tracking_id BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'schema_versions'
          AND column_name = 'generation_id'
    ) THEN
        ALTER TABLE flashback.schema_versions ADD COLUMN generation_id BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'schema_versions'
          AND column_name = 'stream_id'
    ) THEN
        ALTER TABLE flashback.schema_versions ADD COLUMN stream_id BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'schema_versions'
          AND column_name = 'source_xid'
    ) THEN
        ALTER TABLE flashback.schema_versions ADD COLUMN source_xid BIGINT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'schema_versions'
          AND column_name = 'committed_at'
    ) THEN
        ALTER TABLE flashback.schema_versions ADD COLUMN committed_at TIMESTAMPTZ;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'flashback' AND table_name = 'schema_versions'
          AND column_name = 'commit_lsn'
    ) THEN
        ALTER TABLE flashback.schema_versions ADD COLUMN commit_lsn PG_LSN;
    END IF;

    -- Legacy snapshot ownership stays NULL. An OID may have been recycled
    -- after DROP/recreate, so rel_oid equality is not proof of stable tracking
    -- ownership. Only the exact-boundary runtime may populate tracking_id.

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.snapshots'::regclass
          AND conname = 'snapshots_payload_state_check'
    ) THEN
        ALTER TABLE flashback.snapshots
            ADD CONSTRAINT snapshots_payload_state_check
            CHECK (payload_state IN ('available', 'retired', 'missing'));
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.snapshots'::regclass
          AND conname = 'snapshots_payload_state_shape_check'
    ) THEN
        ALTER TABLE flashback.snapshots
            ADD CONSTRAINT snapshots_payload_state_shape_check
            CHECK (
                (payload_state = 'available' AND retired_at IS NULL)
                OR (payload_state IN ('retired', 'missing') AND retired_at IS NOT NULL)
            );
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.snapshots'::regclass
          AND conname = 'snapshots_snapshot_tracking_key'
    ) THEN
        ALTER TABLE flashback.snapshots
            ADD CONSTRAINT snapshots_snapshot_tracking_key
            UNIQUE (snapshot_id, tracking_id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.snapshots'::regclass
          AND conname = 'snapshots_snapshot_tracking_lsn_key'
    ) THEN
        ALTER TABLE flashback.snapshots
            ADD CONSTRAINT snapshots_snapshot_tracking_lsn_key
            UNIQUE (snapshot_id, tracking_id, snapshot_lsn);
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.snapshots'::regclass
          AND conname = 'snapshots_tracking_fk'
          AND confrelid <> 'flashback.tracking_lifecycles'::regclass
    ) THEN
        ALTER TABLE flashback.snapshots
            DROP CONSTRAINT snapshots_tracking_fk;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'flashback.snapshots'::regclass
          AND conname = 'snapshots_tracking_fk'
    ) THEN
        ALTER TABLE flashback.snapshots
            ADD CONSTRAINT snapshots_tracking_fk
            FOREIGN KEY (tracking_id)
            REFERENCES flashback.tracking_lifecycles(tracking_id)
            ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED;
    END IF;
END
$$;

